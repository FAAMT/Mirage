#!/usr/bin/env python3
"""
gen_exp_rom.py — emit rtl_v2/core/exp_rom.vhd, a synchronous exp() ROM.

    ./tools/gen_exp_rom.py

WHY A TABLE AND NOT A POLYNOMIAL
--------------------------------
v2 first tried a degree-2 Horner evaluation, as v1's taylor_exp did. It
does not work over the range softmax needs: a parabola fitted to exp on
[-8, 0] turns back upward, and the measured worst-case absolute error was
0.98 -- i.e. no better than returning a constant. Higher degree, or proper
range reduction (exp(z) = 2^-n * 2^-f, polynomial only on the fractional
part), would both work but cost multipliers and pipeline depth.

A table is better on every axis that matters here:

  * exact to table resolution, no approximation error to tune
  * ONE RAMB36, and BRAM is the resource v2 is trying to use
  * 1-cycle latency, trivially pipelined, no DSP
  * retunable by re-running this script; no RTL edit

RESOLUTION
----------
z arrives in Q(EXP_FRAC) = Q12 and is clamped to [-8, 0]. That spans
8 * 4096 = 32768 Q12 codes, decimated by 2^SHIFT into ENTRIES buckets.
Output is Q16 so the top of the range keeps precision.

With 2048 entries the z step is 0.0039. Accuracy is reported below as the
error in the resulting softmax PROBABILITIES rather than as a per-entry
relative error, because the latter is dominated by the deep end of the
range where exp(-8) = 0.000335 and contributes nothing to any sum.
"""
import math
import pathlib

ENTRIES  = 2048          # one RAMB36 at 18 bits wide
EXP_FRAC = 12            # input Q format, matches mirage_v2_pkg
OUT_FRAC = 16            # output Q format
Z_MIN    = -8.0          # clamp floor
SHIFT    = 4             # (-z) >> SHIFT indexes the table
OUT_W    = 18            # bits per entry; 1.0 in Q16 is 65536, needs 17

assert (-Z_MIN) * (2 ** EXP_FRAC) / (2 ** SHIFT) == ENTRIES, "range/shift/entries disagree"

vals = []
for i in range(ENTRIES):
    z = -(i * (2 ** SHIFT)) / (2 ** EXP_FRAC)     # z at the bucket floor
    vals.append(min(int(round(math.exp(z) * (2 ** OUT_FRAC))), (2 ** OUT_FRAC)))

# Per-entry relative error is a MISLEADING metric here: it is dominated by
# the deep end, where exp(-8) = 0.000335 quantises to 22 in Q16 so a 1-LSB
# rounding looks like 4%. Those terms contribute nothing to a softmax sum
# that a term near exp(0) = 1.0 dominates.
#
# So measure what actually matters: the error in the resulting softmax
# PROBABILITIES, over random score rows, plus how often the argmax moves.
def softmax_rom(scores):
    m = max(scores)
    idx = [min(ENTRIES - 1, max(0, (-(int(round((s - m) * (2 ** EXP_FRAC)))) >> SHIFT)))
           for s in scores]
    e = [vals[i] for i in idx]
    tot = sum(e)
    return [x / tot if tot else 0.0 for x in e]


def softmax_exact(scores):
    m = max(scores)
    e = [math.exp(s - m) for s in scores]
    t = sum(e)
    return [x / t for x in e]


import random
random.seed(7)
prob_err, flips, TRIALS = 0.0, 0, 20000
for _ in range(TRIALS):
    n = random.choice([4, 8, 16])
    sc = [random.uniform(-6, 6) for _ in range(n)]
    a, b = softmax_rom(sc), softmax_exact(sc)
    prob_err = max(prob_err, max(abs(x - y) for x, y in zip(a, b)))
    if max(range(n), key=lambda i: a[i]) != max(range(n), key=lambda i: b[i]):
        flips += 1

body = []
for i in range(0, ENTRIES, 8):
    row = ", ".join(f'"{v:018b}"' for v in vals[i:i + 8])
    body.append(f"        {row},")
body[-1] = body[-1].rstrip(",")

out = f'''-- =====================================================================
-- exp_rom.vhd — synchronous exp() lookup table  [GENERATED]
--
-- Generated by tools/gen_exp_rom.py. Do not hand-edit: re-run the script.
--
-- {ENTRIES} entries covering z in [{Z_MIN}, 0], indexed by (-z) >> {SHIFT} with z in
-- Q{EXP_FRAC}. Output is exp(z) in Q{OUT_FRAC}, {OUT_W} bits ({2 ** OUT_FRAC} = 1.0).
--
-- ACCURACY, measured over {TRIALS:,} random score rows (the metric that
-- matters -- per-entry relative error is dominated by the deep end, where
-- exp(-8) = 0.000335 and contributes nothing to a softmax sum):
--
--   max absolute error in a softmax probability : {prob_err:.6f}  ({prob_err * 100:.4f} pp)
--   rows where the argmax moved                 : {flips} / {TRIALS:,}
--
-- Both are far inside the int8 activation quantisation that follows.
--
-- Replaces the degree-2 polynomial v2 started with, which had 0.98
-- ABSOLUTE error over this range -- a parabola cannot track exp here.
--
-- Inference: a constant array read inside rising_edge(clk) is the
-- canonical Vivado ROM template and maps to block RAM with INIT strings.
-- {ENTRIES} x {OUT_W} bits = {ENTRIES * OUT_W:,} bits, one RAMB36.
-- =====================================================================

library IEEE;
use IEEE.STD_LOGIC_1164.all;
use IEEE.NUMERIC_STD.all;

library work;
use work.mirage_v2_pkg.all;

entity exp_rom is
    port
    (
        clk   : in  std_logic;
        re    : in  std_logic;
        addr  : in  std_logic_vector(EXP_ROM_AW - 1 downto 0);
        dout  : out std_logic_vector(EXP_ROM_DW - 1 downto 0)
    );
end entity;

architecture rtl of exp_rom is

    type rom_t is array (0 to {ENTRIES - 1}) of std_logic_vector(EXP_ROM_DW - 1 downto 0);

    constant ROM : rom_t := (
{chr(10).join(body)}
    );

    attribute rom_style : string;
    attribute rom_style of ROM : constant is "block";

    signal q : std_logic_vector(EXP_ROM_DW - 1 downto 0);

begin

    dout <= q;

    -- Synchronous read, no reset. Same rules as prim/bram_sdp.
    rd : process (clk)
    begin
        if rising_edge(clk) then
            if re = '1' then
                q <= ROM(to_integer(unsigned(addr)));
            end if;
        end if;
    end process;

end architecture;
'''

p = pathlib.Path(__file__).resolve().parent.parent / "rtl_v2" / "core" / "exp_rom.vhd"
p.write_text(out)
print(f"wrote {p}")
print(f"  entries {ENTRIES} x {OUT_W} bits = {ENTRIES * OUT_W:,} bits (1 RAMB36)")
print(f"  max softmax probability error {prob_err:.6f} ({prob_err * 100:.4f} pp)")
print(f"  argmax disagreements          {flips} / {TRIALS:,}")
