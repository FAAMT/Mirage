#!/usr/bin/env python3
"""
gen_recip_rom.py — emit rtl_v2/core/recip_rom.vhd, the softmax normaliser.

    ./tools/gen_recip_rom.py

WHY THERE IS NO DIVIDER, AND NO PROBABILITIES
---------------------------------------------
Attention output for one (head, query) is

    out[d] = sum over k of  p_k * V[k][d]        where p_k = e_k / sum_e

v1 would have had to materialise every p_k, which means a divide per score.
v2 never forms p_k at all. It feeds the UNNORMALISED exp values straight
into the MAC array as activations,

    acc[d] = sum over k of  e8_k * V[k][d]

and normalises once at the end, because every d in a (head, query) shares
the same sum_e. That turns MAX_TOK divides per output vector into ONE
reciprocal lookup plus HEAD_DIM multiplies the DSP array is already doing.

WHY THE TABLE IS SMALL AND ACCURATE
-----------------------------------
e8_k is the exp value requantised to int8, 0..127. The key observation:
the maximum-scoring element always has z = 0, so exp(z) = 1.0, so its
e8 is exactly 127. Therefore

    sum8 is never below 127, and never above MAX_TOK * 127 = 2032.

That bounded range is what makes a plain table work. Storing

    recip[n] = round(127 * 2^FRAC / n)      for n in [127, 2032]

gives values in [4096, 65536] -- 17 bits, with relative resolution at the
worst end of 1/4096 = 0.024%. A naive 1/n table over an unbounded range
would have needed a leading-zero count and a normalise stage instead.

Entries below 127 cannot occur; they are filled with the n=127 value so a
fault can never produce a wild scale factor.
"""
import pathlib

FRAC    = 16                  # output Q format
ENTRIES = 2048                # indexed directly by sum8 (11 bits)
OUT_W   = 18                  # 127 * 2^16 / 127 = 65536 needs 17 bits
INT8_MAX = 127
MIN_SUM = INT8_MAX            # the argmax element always contributes 127
MAX_SUM = 16 * INT8_MAX       # MAX_TOK * 127 = 2032

vals = []
for n in range(ENTRIES):
    eff = max(n, MIN_SUM)                       # clamp the impossible region
    vals.append(min(round(INT8_MAX * (2 ** FRAC) / eff), 2 ** OUT_W - 1))

# Accuracy: worst relative error of the stored reciprocal over the reachable
# range. This one IS the metric that matters -- it scales every output.
worst = max(abs(vals[n] / (INT8_MAX * 2 ** FRAC) - 1.0 / n) * n
            for n in range(MIN_SUM, MAX_SUM + 1))

body = []
for i in range(0, ENTRIES, 8):
    body.append("        " + ", ".join(f'"{v:018b}"' for v in vals[i:i + 8]) + ",")
body[-1] = body[-1].rstrip(",")

out = f'''-- =====================================================================
-- recip_rom.vhd — softmax normalisation reciprocal  [GENERATED]
--
-- Generated by tools/gen_recip_rom.py. Do not hand-edit: re-run it.
--
--     recip[n] = round({INT8_MAX} * 2^{FRAC} / n)
--
-- Indexed by sum8, the sum of the int8-requantised exp values for one
-- (head, query) row. Multiplying an accumulated output by recip[sum8] and
-- shifting right by {FRAC} yields the int8 attention output directly -- so
-- softmax probabilities are never materialised and there is no divider.
--
-- Reachable index range is [{MIN_SUM}, {MAX_SUM}]: the argmax element always has
-- z = 0, hence exp = 1.0, hence e8 = {INT8_MAX}, so sum8 >= {INT8_MAX}. Indices below
-- that are filled with the n = {MIN_SUM} value so a fault cannot produce a wild
-- scale factor.
--
-- Worst relative error over the reachable range: {worst * 100:.5f}%
--
-- {ENTRIES} x {OUT_W} bits = {ENTRIES * OUT_W:,} bits, one RAMB36.
-- =====================================================================

library IEEE;
use IEEE.STD_LOGIC_1164.all;
use IEEE.NUMERIC_STD.all;

library work;
use work.mirage_v2_pkg.all;

entity recip_rom is
    port
    (
        clk  : in  std_logic;
        re   : in  std_logic;
        addr : in  std_logic_vector(RECIP_ROM_AW - 1 downto 0);
        dout : out std_logic_vector(RECIP_ROM_DW - 1 downto 0)
    );
end entity;

architecture rtl of recip_rom is

    type rom_t is array (0 to {ENTRIES - 1}) of std_logic_vector(RECIP_ROM_DW - 1 downto 0);

    constant ROM : rom_t := (
{chr(10).join(body)}
    );

    attribute rom_style : string;
    attribute rom_style of ROM : constant is "block";

    signal q : std_logic_vector(RECIP_ROM_DW - 1 downto 0);

begin

    dout <= q;

    rd : process (clk)
    begin
        if rising_edge(clk) then
            if re = '1' then
                q <= ROM(to_integer(unsigned(addr)));
            end if;
        end if;
    end process;

end architecture;
'''

p = pathlib.Path(__file__).resolve().parent.parent / "rtl_v2" / "core" / "recip_rom.vhd"
p.write_text(out)
print(f"wrote {p}")
print(f"  {ENTRIES} x {OUT_W} bits = {ENTRIES * OUT_W:,} bits (1 RAMB36)")
print(f"  reachable index range [{MIN_SUM}, {MAX_SUM}]")
print(f"  worst relative error {worst * 100:.5f}%")
